export function HomepageJourney() {
  const [active, setActive] = useState<number | null>(null);
  const panelId = useId();

  return <section id="workflow" aria-labelledby="journey-title" className={`${s.section} ${s.sectionLight}`} data-analytics-surface="homepage-journey" data-analytics-location="homepage-directly-below-hero">
    <div className={s.wrap}>
      <header className={s.header}>
        <h2 id="journey-title">However you measure roofs, <span>there&apos;s an easier and faster way to quote them.</span></h2>
        <p className={s.subhead}>Here&apos;s how it works in our app.</p>
      </header>

      <div className={s.grid}>
        {steps.map((step, index) => <Fragment key={step.label}>
          <button
            type="button"
            className={`${s.step} ${active === index ? s.stepActive : ''}`}
            style={{ '--step-column': index + 1 } as CSSProperties}
            aria-expanded={active === index}
            aria-controls={`${panelId}-${index}`}
            onClick={() => {
              const opening = active !== index;
              setActive(opening ? index : null);
              trackAnalyticsOnly('homepage_journey_step_toggle', { step: step.label, label: step.title, action: opening ? 'expand' : 'collapse' });
            }}
          >
            <span className={s.stepTop}><span className={s.stepNumber}>STEP {step.label}</span><span className={s.stepIcon}><Icon name={step.icon} size={24} /></span></span>
            <strong>{step.title}</strong>
            <span className={s.stepSummary}>{step.summary}</span>
            <span className={s.stepAction}>{active === index ? 'Hide details' : 'Click to see how it works'} <Icon name="chevron" size={18} /></span>
          </button>
          <div id={`${panelId}-${index}`} className={s.expansion} hidden={active !== index}>
            <div className={s.expansionCopy}>
              <h3>{step.heading}</h3>
              <p className={s.intro}>{step.introduction}</p>
              <div className={s.methodList}>
                {step.methods.map(method => <div className={s.method} key={method.title}>
                  <Icon name="check" size={21} /><div><strong>{method.title}</strong><p>{method.body}</p></div>
                </div>)}
              </div>
              <p className={s.outcome}>{step.outcome}</p>
              <Link href={step.learnHref} className={s.learnLink} onClick={() => trackAnalyticsOnly('homepage_journey_learn_more', { step: step.label, destination: step.learnHref })}>{step.learnLabel} <Icon name="arrow" size={18} /></Link>
            </div>
            <div className={s.expansionVisual}>
              <div className={`${s.mediaFrame} ${index === 2 ? s.portraitFrame : ''}`}>
                <img src={step.media} alt={step.mediaAlt} loading="lazy" />
              </div>
              <span className={s.mediaCaption}>Actual QuoteCore+ product view · Illustrative job</span>
            </div>
          </div>
        </Fragment>)}
      </div>
      <div className={s.featuresTeaser}>
        <p><strong>There's more to QuoteCore+.</strong> AI assistance, materials ordering, invoicing and more.</p>
        <Link href="/features">Explore all features <Icon name="arrow" size={18} /></Link>
      </div>
    </div>
  </section>;
}
