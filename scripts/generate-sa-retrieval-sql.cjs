/** Deterministic offline generation only. NEVER connects to or applies to a database. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'app/lib/smart-assistant/retrieval/schema.json'),'utf8'));
const text=JSON.stringify(manifest),hash=crypto.createHash('sha256').update(text).digest('hex');
if(text.includes('$registry$'))throw Error('Invalid registry delimiter');
const template=fs.readFileSync(path.join(__dirname,'sa-retrieval/retrieval.sql.in'),'utf8');
const outputs={
 'backend/supabase/migrations/20260926150000_sa_v2_retrieval.sql':template.replace('__SCHEMA_JSON__',text).replaceAll('__HASH__',hash),
 'app/lib/smart-assistant/retrieval/schema-version.ts':`/** Generated by scripts/generate-sa-retrieval-sql.cjs; do not edit. */\nexport const RETRIEVAL_SCHEMA_HASH = '${hash}';\n`,
};
for(const [file,contents] of Object.entries(outputs)){
 const dest=path.join(root,file);
 if(process.argv.includes('--check')){if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8').replace(/\r\n/g,'\n')!==contents.replace(/\r\n/g,'\n'))throw Error('Generated file drift: '+file);}
 else fs.writeFileSync(dest,contents);
}
console.log(`${process.argv.includes('--check')?'Verified':'Generated'} ${Object.keys(outputs).length} files; ${Object.keys(manifest.sources).length} sources; schema ${hash}`);
